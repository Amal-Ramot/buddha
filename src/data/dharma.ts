export const getCategory = (id: CategoryId) =>
  categories.find((c) => c.id === id)!;

export const getTopic = (slug: string) => topics.find((t) => t.slug === slug);

export const topicsByCategory = (id: CategoryId) =>
  topics.filter((t) => t.category === id);

export type GlossaryEntry = {
  name: string;
  term: string;
  text: string;
  topicSlug: string;
  topicTitle: string;
  category: CategoryId;
};

const isLatin = (s: string) => /^[A-Za-z]/.test(s);

/** המילון נגזר מכל המושגים שבנושאים, בלי כפילויות של אותו מונח. */
export const glossary: GlossaryEntry[] = (() => {
  const seen = new Set<string>();
  const out: GlossaryEntry[] = [];
  for (const t of topics) {
    for (const it of t.items) {
      if (!it.term || !isLatin(it.term)) continue;
      const key = it.term.toLowerCase();
      if (seen.has(key)) continue;
      seen.add(key);
      out.push({
        name: it.name,
        term: it.term,
        text: it.text,
        topicSlug: t.slug,
        topicTitle: t.title,
        category: t.category,
      });
    }
  }
  return out.sort((a, b) => a.term.localeCompare(b.term, "en"));
})();

